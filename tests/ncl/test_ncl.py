@dataclass(frozen=True, slots=True)
class _Tolerance:
    rtol: float
    atol: float


def _assert_close(
    actual: xr.DataArray | np.ndarray,
    expected: np.ndarray,
    tolerance: _Tolerance,
    label: str,
) -> None:
    actual_values = np.asarray(actual)
    difference = actual_values - expected
    scale = float(np.max(np.abs(expected)))
    relative_population = np.abs(expected) > max(scale * 1.0e-12, 1.0e-300)
    relative_error = (
        float(
            np.max(
                np.abs(difference[relative_population] / expected[relative_population])
            )
        )
        if np.any(relative_population)
        else 0.0
    )
    try:
        np.testing.assert_allclose(
            actual_values,
            expected,
            rtol=tolerance.rtol,
            atol=tolerance.atol,
        )
    except AssertionError as error:
        rms = float(np.sqrt(np.mean(difference**2)))
        raise AssertionError(
            f"{label}: max_abs={np.max(np.abs(difference)):.6e}, "
            f"rms={rms:.6e}, max_relative={relative_error:.6e}, "
            f"rtol={tolerance.rtol:.6e}, atol={tolerance.atol:.6e}"
        ) from error


def _common_tolerance(operation: str, grid_kind: str, input_family: str) -> _Tolerance:
    random_gaussian = grid_kind == "gl" and input_family == "random"
    if operation == "gradient":
        return _Tolerance(0.0, 3.0e-6 if random_gaussian else 2.0e-17)
    if operation == "kinematics":
        return _Tolerance(0.0, 4.0e-6 if random_gaussian else 2.0e-17)
    if operation == "inverse_gradient":
        return _Tolerance(0.0, 1.0e-13)
    if operation == "laplacian":
        return _Tolerance(
            0.0, 5.0e-11 if grid_kind == "cc" and input_family == "random" else 1.0e-20
        )
    if operation == "inverse_laplacian":
        if input_family == "random":
            if grid_kind == "cc":
                # Random CC fields stress the highest retained degrees.  The
                # measured absolute difference is 2.40e9 on fields of order
                # 1e12, caused by cancellation in two independent inverses.
                return _Tolerance(3.5e-3, 2.5e9)
            return _Tolerance(3.5e-3, 1.0e6)
        return _Tolerance(1.0e-14, 2.0e-2)
    if operation == "inverse_vector_laplacian":
        if input_family == "random":
            # The measured maxima are 3.34e9 (GL) and 2.37e9 (CC), against
            # fields of order 1e12; retain separate grid-specific bounds.
            return _Tolerance(3.5e-3, 3.5e9 if grid_kind == "gl" else 2.5e9)
        return _Tolerance(1.0e-14, 2.0e-2)
    if operation == "potential":
        if random_gaussian:
            # High-degree GL vector analysis differs most after inverse
            # Laplacian scaling; max measured error is 3.14e4.
            return _Tolerance(4.0e-2, 3.3e4)
        return _Tolerance(2.0e-12, 1.0e-6)
    if operation == "helmholtz":
        if random_gaussian:
            return _Tolerance(1.3e-1, 2.7e-1)
        return _Tolerance(0.0, 2.0e-12)
    if operation == "vector_laplacian":
        if input_family == "random":
            # The output itself is order 1e-10; the maximum measured
            # cross-implementation difference is 3.97e-11 on CC.
            return _Tolerance(2.5e-1, 4.2e-11)
        return _Tolerance(0.0, 1.0e-20)
    if operation == "wind":
        return _Tolerance(0.0, 2.0e-12)
    raise AssertionError(f"no NCL parity tolerance for {operation}")


def _spectral_tolerance(
    operation: Literal["filter", "regrid_scalar", "regrid_vector"],
    source_grid: str,
    input_family: str,
    target_grid: str | None,
    domain: str,
    taper: float | None,
) -> _Tolerance:
    if input_family == "analytic":
        return _Tolerance(0.0, 2.0e-11)
    if domain == "R21":
        # After applying the independent m<=21 boundary, the measured
        # maxima are 1.73e-5 (hard) and 1.42e-5 (taper) for scalar cases;
        # vector cases remain below 1.55e-5.
        return _Tolerance(0.0, 3.0e-5 if taper is None else 2.5e-5)
    if domain == "full":
        if operation == "filter":
            return _Tolerance(0.0, 2.0e-13)
        if operation == "regrid_scalar":
            same_grid = source_grid == target_grid
            return _Tolerance(0.0, 2.0e-13 if same_grid else 1.2e-5)
        return _Tolerance(0.0, 0.4)
    if taper is None:
        # Broadband random maxima are 3.46e-4 for scalar and 9.76e-4 for
        # vector regridding across the four grid-direction combinations.
        return _Tolerance(
            0.0,
            4.0e-4 if operation != "regrid_vector" else 1.1e-3,
        )
    # Tapered maxima are 1.20e-4 for scalar and 2.80e-4 for vector cases.
    return _Tolerance(
        0.0,
        1.5e-4 if operation != "regrid_vector" else 3.5e-4,
    )


def _fields(
    arrays: dict[str, np.ndarray],
    grid_kind: Literal["gl", "cc"],
    latitude_order: Literal["ascending", "descending"] = "ascending",
) -> tuple[xr.DataArray, xr.DataArray, xr.DataArray]:
    return cast(
        tuple[xr.DataArray, xr.DataArray, xr.DataArray],
        tuple(
            data_array(arrays, name, grid_kind, latitude_order=latitude_order)
            for name in ("scalar", "u", "v")
        ),
    )


@pytest.mark.parametrize(("grid_kind", "input_family"), _REFERENCE_CASES)
def test_ncl_reference_schema(
    grid_kind: Literal["gl", "cc"], input_family: Literal["analytic", "random"]
) -> None:
    arrays, metadata = load_reference(grid_kind, input_family)
    source = grid(grid_kind)
    assert metadata["schema_version"] == SCHEMA_VERSION
    assert metadata["ncl_version"] == "6.6.2"
    assert metadata["reference"] == "NCL 6.6.2 built-in SPHEREPACK"
    assert metadata["earth_radius_m"] == sg.EARTH_RADIUS_M
    assert metadata["latitude_order"] == "ascending"
    assert metadata["longitude_convention"] == "0_to_360_noncyclic"
    assert metadata["array_keys"] == sorted(arrays)
    np.testing.assert_array_equal(arrays["lat"], source.latitude)
    np.testing.assert_array_equal(arrays["lon"], source.longitude)
    assert arrays["scalar"].shape == (source.nlat, source.nlon)
    assert arrays["u"].shape == arrays["v"].shape == arrays["scalar"].shape
    assert arrays["lon"][0] == 0.0
    assert arrays["lon"][-1] < 360.0
    for target_kind in GRID_KINDS:
        target = grid(target_kind)
        np.testing.assert_array_equal(
            arrays[f"target_lat_{target_kind}"], target.latitude
        )
        np.testing.assert_array_equal(
            arrays[f"target_lon_{target_kind}"], target.longitude
        )


@pytest.mark.parametrize(("grid_kind", "input_family"), _REFERENCE_CASES)
def test_ncl_taper_weights(
    grid_kind: Literal["gl", "cc"], input_family: Literal["analytic", "random"]
) -> None:
    arrays, metadata = load_reference(grid_kind, input_family)
    degree = np.arange(43, dtype=np.float64)
    expected = np.ones(43, dtype=np.float64)
    expected[1:] = np.exp(
        np.log(float(metadata["taper"]))
        * (degree[1:] * (degree[1:] + 1.0) / (42.0 * 43.0)) ** 2
    )
    _assert_close(
        arrays["taper_weights"],
        expected,
        _Tolerance(0.0, 5.0e-16),
        f"{grid_kind}-{input_family}-taper-weights",
    )
    assert arrays["taper_weights"][-1] == pytest.approx(0.1, abs=5.0e-16)



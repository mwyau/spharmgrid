@pytest.mark.parametrize(("grid_kind", "input_family"), _REFERENCE_CASES)
@pytest.mark.parametrize(
    "operation",
    ["filter", "gradient", "vorticity", "regrid", "regrid_vector"],
    ids=lambda operation: f"descending-{operation}",
)
def test_ncl_descending_latitude_normalization(
    grid_kind: Literal["gl", "cc"],
    input_family: Literal["analytic", "random"],
    operation: str,
) -> None:
    arrays, _ = load_reference(grid_kind, input_family)
    scalar, u, v = _fields(arrays, grid_kind, latitude_order="descending")
    if operation == "filter":
        actual = sg.filter(scalar, truncation="T42x10", taper=0.1, sht_threads=1)
        _assert_close(
            actual,
            expected_values(
                arrays, "filter_T42x10_taper", grid_kind, latitude_order="descending"
            ),
            _spectral_tolerance("filter", grid_kind, input_family, None, "T42x10", 0.1),
            f"{grid_kind}-{input_family}-descending-filter",
        )
    elif operation == "gradient":
        actual = sg.gradient(scalar, sht_threads=1)
        for name in ("gradient_eastward", "gradient_northward"):
            _assert_close(
                actual[name],
                expected_values(arrays, name, grid_kind, latitude_order="descending"),
                _common_tolerance("gradient", grid_kind, input_family),
                f"{grid_kind}-{input_family}-descending-{name}",
            )
    elif operation == "vorticity":
        actual = sg.vorticity(u, v, sht_threads=1)
        _assert_close(
            actual,
            expected_values(
                arrays, "vorticity", grid_kind, latitude_order="descending"
            ),
            _common_tolerance("kinematics", grid_kind, input_family),
            f"{grid_kind}-{input_family}-descending-vorticity",
        )
    elif operation == "regrid":
        target = "cc" if grid_kind == "gl" else "gl"
        actual = sg.regrid(scalar, grid(target), truncation="T42", sht_threads=1)
        _assert_close(
            actual,
            expected_values(
                arrays,
                f"regrid_scalar_{target}_T42_hard",
                grid_kind,
                target_grid=target,
            ),
            _spectral_tolerance(
                "regrid_scalar", grid_kind, input_family, target, "T42", None
            ),
            f"{grid_kind}-{input_family}-descending-regrid",
        )
    else:
        target = "cc" if grid_kind == "gl" else "gl"
        actual = sg.regrid_vector(u, v, grid(target, "descending"), sht_threads=1)
        tolerance = _spectral_tolerance(
            "regrid_vector", grid_kind, input_family, target, "full", None
        )
        for component in ("u", "v"):
            key = f"regrid_vector_{component}_{target}_full_hard"
            _assert_close(
                actual[component],
                expected_values(
                    arrays,
                    key,
                    grid_kind,
                    latitude_order="descending",
                    target_grid=target,
                ),
                tolerance,
                f"{grid_kind}-{input_family}-descending-{key}",
            )

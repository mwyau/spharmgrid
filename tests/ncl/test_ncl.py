@pytest.mark.parametrize(("grid_kind", "input_family"), _REFERENCE_CASES)
@pytest.mark.parametrize(
    "operation", _VECTOR_OPERATIONS, ids=lambda operation: f"vector-{operation}"
)
def test_ncl_vector_operators(
    grid_kind: Literal["gl", "cc"],
    input_family: Literal["analytic", "random"],
    operation: str,
) -> None:
    arrays, _ = load_reference(grid_kind, input_family)
    _, u, v = _fields(arrays, grid_kind)
    tolerance_operation = {
        "vorticity": "kinematics",
        "divergence": "kinematics",
        "kinematics": "kinematics",
        "streamfunction": "potential",
        "velocity_potential": "potential",
        "potentials": "potential",
        "rotational_wind": "wind",
        "divergent_wind": "wind",
        "wind_vorticity_divergence": "wind",
        "wind_potentials": "wind",
        "helmholtz": "helmholtz",
        "vector_laplacian": "vector_laplacian",
        "inverse_vector_laplacian": "inverse_vector_laplacian",
    }[operation]
    tolerance = _common_tolerance(tolerance_operation, grid_kind, input_family)
    if operation == "vorticity":
        actual = sg.vorticity(u, v, sht_threads=1)
        outputs = (("vorticity", actual),)
    elif operation == "divergence":
        actual = sg.divergence(u, v, sht_threads=1)
        outputs = (("divergence", actual),)
    elif operation == "kinematics":
        actual = sg.kinematics(u, v, sht_threads=1)
        outputs = (("vorticity", actual["vo"]), ("divergence", actual["d"]))
    elif operation == "streamfunction":
        outputs = (("streamfunction", sg.streamfunction(u, v, sht_threads=1)),)
    elif operation == "velocity_potential":
        outputs = (("velocity_potential", sg.velocity_potential(u, v, sht_threads=1)),)
    elif operation == "potentials":
        actual = sg.potentials(u, v, sht_threads=1)
        outputs = (
            ("streamfunction", actual["strf"]),
            ("velocity_potential", actual["vp"]),
        )
    elif operation == "rotational_wind":
        actual = sg.rotational_wind(
            data_array(arrays, "vorticity", grid_kind),
            source="vorticity",
            sht_threads=1,
        )
        outputs = (
            ("rotational_u", actual["u_rotational"]),
            ("rotational_v", actual["v_rotational"]),
        )
    elif operation == "divergent_wind":
        actual = sg.divergent_wind(
            data_array(arrays, "divergence", grid_kind),
            source="divergence",
            sht_threads=1,
        )
        outputs = (
            ("divergent_u", actual["u_divergent"]),
            ("divergent_v", actual["v_divergent"]),
        )
    elif operation == "wind_vorticity_divergence":
        actual = sg.wind(
            data_array(arrays, "vorticity", grid_kind),
            data_array(arrays, "divergence", grid_kind),
            source="vorticity_divergence",
            sht_threads=1,
        )
        outputs = (("wind_vo_d_u", actual["u"]), ("wind_vo_d_v", actual["v"]))
    elif operation == "wind_potentials":
        actual = sg.wind(
            data_array(arrays, "streamfunction", grid_kind),
            data_array(arrays, "velocity_potential", grid_kind),
            source="potentials",
            sht_threads=1,
        )
        outputs = (
            ("wind_potentials_u", actual["u"]),
            ("wind_potentials_v", actual["v"]),
        )
    elif operation == "helmholtz":
        actual = sg.helmholtz(u, v, sht_threads=1)
        outputs = (
            ("helmholtz_u_rotational", actual["u_rotational"]),
            ("helmholtz_v_rotational", actual["v_rotational"]),
            ("helmholtz_u_divergent", actual["u_divergent"]),
            ("helmholtz_v_divergent", actual["v_divergent"]),
        )
    elif operation == "vector_laplacian":
        actual = sg.vector_laplacian(u, v, sht_threads=1)
        outputs = (
            ("vector_laplacian_u", actual["u"]),
            ("vector_laplacian_v", actual["v"]),
        )
    else:
        actual = sg.inverse_vector_laplacian(u, v, sht_threads=1)
        outputs = (
            ("inverse_vector_laplacian_u", actual["u"]),
            ("inverse_vector_laplacian_v", actual["v"]),
        )
    for name, result in outputs:
        _assert_close(
            result,
            arrays[name],
            tolerance,
            f"{grid_kind}-{input_family}-{operation}-{name}",
        )


